package com.consultorio.security;

import com.consultorio.repository.AuditLogRepository;
import com.consultorio.repository.ConfiguracionSistemaRepository;
import com.consultorio.repository.UsuarioRepository;
import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.MigrationInfo;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.data.domain.PageRequest;
import org.springframework.test.context.TestPropertySource;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

@SpringBootTest
@TestPropertySource(properties = {
        "spring.datasource.url=jdbc:h2:mem:flywayvalidatedb;MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
        "spring.datasource.driverClassName=org.h2.Driver",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "spring.jpa.hibernate.ddl-auto=validate",
        "spring.flyway.enabled=true",
        "spring.flyway.baseline-on-migrate=true",
        "spring.flyway.baseline-version=1",
        "spring.flyway.locations=classpath:db/migration/common,classpath:db/migration/{vendor}"
})
class FlywaySchemaValidationTest {

    @Autowired
    private Flyway flyway;

    @Autowired
    private ConfiguracionSistemaRepository configuracionSistemaRepository;

    @Autowired
    private UsuarioRepository usuarioRepository;

    @Autowired
    private AuditLogRepository auditLogRepository;

    @Test
    @DisplayName("S9: Flyway migrations V1+V2 bootstrap clean schema that passes Hibernate ddl-auto=validate")
    void flywayMigrationsPassHibernateSchemaValidation() {
        assertThat(flyway.info().applied()).hasSizeGreaterThanOrEqualTo(2);
        assertThat(configuracionSistemaRepository.findById(1L)).isPresent();
        assertThat(usuarioRepository.count()).isGreaterThanOrEqualTo(1L);
        assertThat(auditLogRepository.findAllByOrderByOccurredAtDescIdDesc(PageRequest.of(0, 5))).isNotNull();
    }

    @Test
    @DisplayName("S9: Pre-existing non-empty database baselines at V1 and applies V2 idempotently without losing existing users")
    void preExistingDatabaseBaselinesAtV1AndAppliesV2() throws Exception {
        String legacyUrl = "jdbc:h2:mem:flywaylegacydb;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
        try (Connection conn = DriverManager.getConnection(legacyUrl, "sa", "");
             Statement st = conn.createStatement()) {
            st.execute("""
                    CREATE TABLE usuarios (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        email VARCHAR(255) NOT NULL UNIQUE,
                        password VARCHAR(255) NOT NULL,
                        rol VARCHAR(255) NOT NULL,
                        activo BOOLEAN NOT NULL DEFAULT TRUE,
                        email_verificado BOOLEAN NOT NULL DEFAULT FALSE,
                        google_calendar_connected BOOLEAN NOT NULL DEFAULT FALSE
                    )
                    """);
            st.execute("""
                    CREATE TABLE pacientes (
                        id UUID PRIMARY KEY,
                        nombre VARCHAR(100) NOT NULL,
                        apellido VARCHAR(100) NOT NULL
                    )
                    """);
            st.execute("""
                    CREATE TABLE turnos (
                        id UUID PRIMARY KEY,
                        estado VARCHAR(50) NOT NULL
                    )
                    """);
            st.execute("INSERT INTO usuarios (email, password, rol) VALUES ('legacy@test.com', 'hash', 'PACIENTE')");
        }

        Flyway legacyFlyway = Flyway.configure()
                .dataSource(legacyUrl, "sa", "")
                .baselineOnMigrate(true)
                .baselineVersion("1")
                .locations("classpath:db/migration/common", "classpath:db/migration/{vendor}")
                .load();

        legacyFlyway.migrate();

        MigrationInfo[] applied = legacyFlyway.info().applied();
        assertThat(applied).hasSize(2);
        assertThat(applied[0].getVersion().getVersion()).isEqualTo("1");
        assertThat(applied[1].getVersion().getVersion()).isEqualTo("2");

        try (Connection conn = DriverManager.getConnection(legacyUrl, "sa", "");
             Statement st = conn.createStatement()) {
            try (ResultSet rs = st.executeQuery("SELECT auth_provider, token_version FROM usuarios WHERE email = 'legacy@test.com'")) {
                assertThat(rs.next()).isTrue();
                assertThat(rs.getString("auth_provider")).isEqualTo("LOCAL");
                assertThat(rs.getInt("token_version")).isEqualTo(0);
            }
            try (ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM configuracion_sistema WHERE id = 1")) {
                assertThat(rs.next()).isTrue();
                assertThat(rs.getInt(1)).isEqualTo(1);
            }
            try (ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM audit_log")) {
                assertThat(rs.next()).isTrue();
                assertThat(rs.getInt(1)).isEqualTo(0);
            }
        }
    }
}
