CREATE TABLE IF NOT EXISTS configuracion_sistema (
    id BIGINT PRIMARY KEY,
    resumen_diario_medicos_habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    resumen_semanal_medicos_habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_modificacion TIMESTAMP,
    modificado_por VARCHAR(100)
);

INSERT INTO configuracion_sistema (id, resumen_diario_medicos_habilitado, resumen_semanal_medicos_habilitado)
SELECT 1, TRUE, TRUE
WHERE NOT EXISTS (SELECT 1 FROM configuracion_sistema WHERE id = 1);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    outcome VARCHAR(32) NOT NULL,
    actor_user_id BIGINT,
    actor_role VARCHAR(32),
    target_type VARCHAR(64),
    target_id VARCHAR(64),
    summary VARCHAR(255)
);

CREATE INDEX IF NOT EXISTS idx_audit_log_occurred_at ON audit_log (occurred_at);
CREATE INDEX IF NOT EXISTS idx_audit_log_event_type ON audit_log (event_type);
