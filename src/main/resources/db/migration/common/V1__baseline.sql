-- ISO/IEC 27001 A.8.9 / A.8.32: Baseline schema for Sistema de Gestion de Turnos
-- Compatible with PostgreSQL and H2 (MODE=PostgreSQL)

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    bloqueado BOOLEAN DEFAULT FALSE,
    email_verificado BOOLEAN NOT NULL DEFAULT FALSE,
    token_verificacion_email VARCHAR(255),
    token_verificacion_expiracion TIMESTAMP,
    token_restablecimiento_password VARCHAR(255),
    token_restablecimiento_expiracion TIMESTAMP,
    nueva_password_pendiente VARCHAR(255),
    google_access_token VARCHAR(2048),
    google_refresh_token VARCHAR(2048),
    google_token_expiry BIGINT,
    google_calendar_connected BOOLEAN NOT NULL DEFAULT FALSE,
    google_id VARCHAR(255),
    auth_provider VARCHAR(255) DEFAULT 'LOCAL',
    token_version INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS especialidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS doctores (
    id UUID PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id),
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    foto_url VARCHAR(500),
    disponible_para_turnos BOOLEAN DEFAULT TRUE,
    tiene_advertencia_bloqueante BOOLEAN DEFAULT FALSE,
    mensaje_advertencia_bloqueante VARCHAR(1000),
    tiene_advertencia_informativa BOOLEAN DEFAULT FALSE,
    mensaje_advertencia_informativa VARCHAR(1000)
);

CREATE INDEX IF NOT EXISTS idx_doctores_usuario ON doctores (usuario_id);

CREATE TABLE IF NOT EXISTS doctor_especialidades (
    doctor_id UUID NOT NULL REFERENCES doctores(id),
    especialidad_id BIGINT NOT NULL REFERENCES especialidades(id),
    PRIMARY KEY (doctor_id, especialidad_id)
);

CREATE TABLE IF NOT EXISTS pacientes (
    id UUID PRIMARY KEY,
    usuario_id BIGINT UNIQUE REFERENCES usuarios(id),
    tutor_id UUID REFERENCES pacientes(id),
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    dni BIGINT UNIQUE,
    telefono VARCHAR(50),
    email VARCHAR(100),
    fecha_nacimiento DATE
);

CREATE INDEX IF NOT EXISTS idx_pacientes_dni ON pacientes (dni);
CREATE INDEX IF NOT EXISTS idx_pacientes_usuario ON pacientes (usuario_id);
CREATE INDEX IF NOT EXISTS idx_pacientes_tutor ON pacientes (tutor_id);

CREATE TABLE IF NOT EXISTS horarios_atencion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id UUID NOT NULL REFERENCES doctores(id),
    especialidad_id BIGINT REFERENCES especialidades(id),
    dia_semana VARCHAR(255),
    fecha DATE,
    fecha_desde DATE,
    fecha_hasta DATE,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    duracion_turno_minutos INTEGER NOT NULL DEFAULT 30
);

CREATE TABLE IF NOT EXISTS slots_horario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id UUID NOT NULL REFERENCES doctores(id),
    especialidad_id BIGINT REFERENCES especialidades(id),
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    duracion_minutos INTEGER NOT NULL DEFAULT 30,
    es_puntual BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_slots_doctor_fecha ON slots_horario (doctor_id, fecha);

CREATE TABLE IF NOT EXISTS plantillas_agenda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id UUID NOT NULL REFERENCES doctores(id),
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS detalles_plantilla (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plantilla_id BIGINT NOT NULL REFERENCES plantillas_agenda(id),
    especialidad_id BIGINT REFERENCES especialidades(id),
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    duracion_turno_minutos INTEGER NOT NULL DEFAULT 30
);

CREATE TABLE IF NOT EXISTS turnos (
    id UUID PRIMARY KEY,
    version BIGINT,
    paciente_id UUID NOT NULL REFERENCES pacientes(id),
    doctor_id UUID NOT NULL REFERENCES doctores(id),
    especialidad_id BIGINT NOT NULL REFERENCES especialidades(id),
    fecha_hora TIMESTAMP NOT NULL,
    estado VARCHAR(50) NOT NULL DEFAULT 'PENDIENTE',
    motivo_consulta VARCHAR(500),
    motivo_cancelacion VARCHAR(500),
    tiene_obra_social BOOLEAN NOT NULL DEFAULT FALSE,
    obra_social VARCHAR(150),
    recordatorio48hs_enviado BOOLEAN NOT NULL DEFAULT FALSE,
    google_event_id VARCHAR(255),
    google_event_id_doctor VARCHAR(255),
    google_event_id_secretaria VARCHAR(255)
);

CREATE INDEX IF NOT EXISTS idx_turnos_doctor_fecha ON turnos (doctor_id, fecha_hora);
CREATE INDEX IF NOT EXISTS idx_turnos_paciente_fecha ON turnos (paciente_id, fecha_hora);
CREATE INDEX IF NOT EXISTS idx_turnos_estado ON turnos (estado);

CREATE TABLE IF NOT EXISTS configuracion_sistema (
    id BIGINT PRIMARY KEY,
    resumen_diario_medicos_habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    resumen_semanal_medicos_habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_modificacion TIMESTAMP,
    modificado_por VARCHAR(100)
);

INSERT INTO configuracion_sistema (id, resumen_diario_medicos_habilitado, resumen_semanal_medicos_habilitado)
SELECT 1, TRUE, TRUE
WHERE NOT EXISTS (SELECT 1 FROM configuracion_sistema WHERE id = 1);
